// Kept outside this script so the CI can bump it on every push to main (docs/release.md).
val appVersion = Properties().apply {
    load(providers.fileContents(layout.projectDirectory.file("version.properties")).asText.get().reader())
}

android {
    namespace = "org.opensources.umai"
    compileSdk = 37
    // The first NDK whose platform headers reach API 37, the app's minimum.
    ndkVersion = "30.0.16248370"

    defaultConfig {
        applicationId = "org.opensources.umai"
        minSdk = 37
        targetSdk = 37
        versionCode = checkNotNull(appVersion.getProperty("versionCode")).toInt()
        versionName = checkNotNull(appVersion.getProperty("versionName"))

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        // The on-device language model (llama.cpp) is built for 64-bit ARM only:
        // every phone that runs Android 17 has it, and a model this size would
        // not run usefully on anything else.
        ndk {
            abiFilters += "arm64-v8a"
        }
        externalNativeBuild {
            cmake {
                arguments += listOf(
                    "-DCMAKE_BUILD_TYPE=Release",
                    // Shared by every variant, so llama.cpp is downloaded once.
                    "-DUMAI_LLAMA_CACHE=${layout.buildDirectory.dir("llama.cpp").get().asFile.invariantSeparatorsPath}",
                )
            }
        }
    }

    externalNativeBuild {
        cmake {
            path = file("src/main/cpp/CMakeLists.txt")
        }
    }

    androidResources {
        // Umai ships English (default) and French; any other system language
        // falls back to the default resources, i.e. English.
        localeFilters += setOf("en", "fr")
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            isMinifyEnabled = false
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
        }
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}")
        // llama.cpp picks its CPU backend by scanning the native library
        // directory for the variant that suits the processor; left inside the
        // APK, the libraries are not in that directory and none is found.
        jniLibs.useLegacyPackaging = true
    }

    lint {
        warningsAsErrors = false
        abortOnError = true
        // PropertyEscape only ever fires on `local.properties`, a machine-local
        // file that is generated by the IDE, excluded from git and never
        // shipped; on Windows it flags the SDK path whichever way it is written.
        disable += "PropertyEscape"
        // The app is built for arm64-v8a only, on purpose: the on-device language
        // model it bundles llama.cpp for would not run usefully on x86_64 hardware.
        disable += "ChromeOsAbiSupport"
        checkDependencies = true
    }
}

